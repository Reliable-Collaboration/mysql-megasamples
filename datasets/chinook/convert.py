#!/usr/bin/env python3
"""Chinook: rewrite the upstream MySQL script for MySQL 9.7 and this project's naming convention.

Transformations, all applied OUTSIDE string literals and comments by a scanner rather than by regex,
because the data contains apostrophes, commas and capital letters that a blind substitution would
corrupt (a value ending in N immediately before its closing quote is the obvious trap):

  `MixedCase`   -> `lowercase`   identifiers only; backticks never appear in Chinook's data
  NVARCHAR(n)   -> VARCHAR(n)    NVARCHAR is a utf8mb3 synonym; the server default is utf8mb4
  N'...'        -> '...'         the national-charset prefix, likewise utf8mb3
  `Chinook`     -> `chinook`     falls out of identifier lower-casing

Record: knowledge/datasets/chinook.md   Decision: knowledge/decisions/chinook-conversion-path.md
"""
import re, sys


def transform(sql):
    """Walk the script once, tracking string/comment context, and emit the rewritten text."""
    out, i, n = [], 0, len(sql)
    renames = {}
    while i < n:
        ch = sql[i]
        # --- string literal: copy verbatim, honouring '' and backslash escapes -----------
        if ch == "'":
            out.append(ch); i += 1
            while i < n:
                if sql[i] == "\\" and i + 1 < n:
                    out.append(sql[i:i + 2]); i += 2; continue
                if sql[i] == "'":
                    if i + 1 < n and sql[i + 1] == "'":
                        out.append("''"); i += 2; continue
                    out.append("'"); i += 1; break
                out.append(sql[i]); i += 1
            continue
        # --- comments: copy verbatim ----------------------------------------------------
        if sql.startswith("/*", i):
            end = sql.find("*/", i + 2)
            end = n if end < 0 else end + 2
            out.append(sql[i:end]); i = end; continue
        if sql.startswith("--", i):
            end = sql.find("\n", i)
            end = n if end < 0 else end
            out.append(sql[i:end]); i = end; continue
        # --- backtick-quoted identifier: lower-case it ----------------------------------
        if ch == "`":
            end = sql.find("`", i + 1)
            if end > 0:
                ident = sql[i + 1:end]
                lowered = ident.lower()
                if ident != lowered:
                    renames[ident] = lowered
                out.append(f"`{lowered}`"); i = end + 1; continue
        # --- N'...' national-string prefix ----------------------------------------------
        if ch in "Nn" and i + 1 < n and sql[i + 1] == "'" and (i == 0 or not (sql[i - 1].isalnum() or sql[i - 1] == "_")):
            i += 1; continue          # drop the prefix; the literal is copied on the next pass
        # --- NVARCHAR type --------------------------------------------------------------
        m = re.match(r"NVARCHAR\s*\(", sql[i:], re.I)
        if m and (i == 0 or not (sql[i - 1].isalnum() or sql[i - 1] == "_")):
            out.append("VARCHAR("); i += m.end(); continue
        out.append(ch); i += 1
    return "".join(out), renames


def main():
    src, dest, mapfile = sys.argv[1], sys.argv[2], sys.argv[3]
    sql = open(src, encoding="utf-8").read()
    converted, renames = transform(sql)
    for bad in ("NVARCHAR", "NCHAR"):
        # only flag occurrences outside strings; re-scan the output the same way
        if re.search(rf"(?<![A-Za-z0-9_]){bad}\s*\(", converted, re.I):
            sys.exit(f"{bad} survived the conversion")
    open(dest, "w", encoding="utf-8").write(converted)
    with open(mapfile, "w", encoding="utf-8") as fh:
        fh.write("# Generated by datasets/chinook/convert.py: upstream identifier -> MySQL identifier.\n")
        fh.write("# Only case changes; no name is otherwise altered.\n")
        for old, new in sorted(renames.items()):
            fh.write(f"{old}: {new}\n")
    print(f"  . converted {len(sql):,} -> {len(converted):,} bytes, {len(renames)} identifiers lower-cased")


if __name__ == "__main__":
    main()
