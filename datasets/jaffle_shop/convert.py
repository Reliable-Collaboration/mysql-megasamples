#!/usr/bin/env python3
"""Jaffle Shop (classic seeds): three raw tables from dbt's teaching project.

The seeds carry no types at all, so every column is declared here. Amounts are integer cents in the
upstream data and are kept that way rather than silently converted to a decimal currency.
Record: knowledge/datasets/jaffle-shop.md
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from megasamples.sources import csvtable  # noqa: E402

CUSTOMERS = [("id", "id", "INT UNSIGNED"), ("first_name", "first_name", "VARCHAR(50)"),
             ("last_name", "last_name", "VARCHAR(50)")]
ORDERS = [("id", "id", "INT UNSIGNED"), ("user_id", "user_id", "INT UNSIGNED"),
          ("order_date", "order_date", "DATE"), ("status", "status", "VARCHAR(20)")]
PAYMENTS = [("id", "id", "INT UNSIGNED"), ("order_id", "order_id", "INT UNSIGNED"),
            ("payment_method", "payment_method", "VARCHAR(20)"), ("amount", "amount", "INT")]


def main():
    downloads, dest = sys.argv[1], sys.argv[2]
    parts = ["-- Jaffle Shop classic seeds. Generated by datasets/jaffle_shop/convert.py.",
             "-- Upstream: dbt-labs/jaffle-shop-classic, Apache-2.0.",
             "SET NAMES utf8mb4;",
             "DROP DATABASE IF EXISTS `jaffle_shop`;",
             "CREATE DATABASE `jaffle_shop` DEFAULT CHARACTER SET utf8mb4;",
             "USE `jaffle_shop`;"]
    counts = {}
    for table, spec, filename in [("raw_customers", CUSTOMERS, "raw_customers.csv"),
                                  ("raw_orders", ORDERS, "raw_orders.csv"),
                                  ("raw_payments", PAYMENTS, "raw_payments.csv")]:
        sql, n = csvtable.emit_table(os.path.join(downloads, filename), table, spec)
        parts.append(sql)
        counts[table] = n
    # the seeds have natural keys and references; declare them rather than leaving the data loose
    parts.append("ALTER TABLE `raw_customers` ADD PRIMARY KEY (`id`);")
    parts.append("ALTER TABLE `raw_orders` ADD PRIMARY KEY (`id`), ADD KEY (`user_id`);")
    parts.append("ALTER TABLE `raw_payments` ADD PRIMARY KEY (`id`), ADD KEY (`order_id`);")
    parts.append("ALTER TABLE `raw_orders` ADD CONSTRAINT `fk_orders_customer` "
                 "FOREIGN KEY (`user_id`) REFERENCES `raw_customers` (`id`);")
    parts.append("ALTER TABLE `raw_payments` ADD CONSTRAINT `fk_payments_order` "
                 "FOREIGN KEY (`order_id`) REFERENCES `raw_orders` (`id`);")
    open(dest, "w", encoding="utf-8").write("\n".join(parts) + "\n")
    print(f"  . converted {counts}")


if __name__ == "__main__":
    main()
