#!/usr/bin/env python3
"""smallsets: three classic teaching tables (Titanic, Iris, Palmer Penguins) in one database.

Each table's columns and types are declared here rather than inferred, and each carries a surrogate
key because none of the three files has a natural one. Layout decision:
knowledge/decisions/smallsets-database-layout.md
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from megasamples.sources import csvtable  # noqa: E402

SPECIES = {"0": "setosa", "1": "versicolor", "2": "virginica"}

TITANIC = [("pclass", "pclass", "TINYINT UNSIGNED"), ("survived", "survived", "TINYINT(1)"),
           ("name", "name", "VARCHAR(100)"), ("sex", "sex", "VARCHAR(6)"),
           ("age", "age", "DECIMAL(6,4)"), ("sibsp", "sibsp", "TINYINT UNSIGNED"),
           ("parch", "parch", "TINYINT UNSIGNED"), ("ticket", "ticket", "VARCHAR(20)"),
           ("fare", "fare", "DECIMAL(9,4)"), ("cabin", "cabin", "VARCHAR(40)"),
           ("embarked", "embarked", "CHAR(1)"), ("boat", "boat", "VARCHAR(8)"),
           ("body", "body", "SMALLINT UNSIGNED"), ("home.dest", "home_dest", "VARCHAR(100)")]

# scikit-learn ships iris in its "bunch" layout: the first line is (n_samples, n_features, target
# names), not column headers, and the class is a 0/1/2 target index rather than a name.
IRIS = [(0, "sepal_length", "DECIMAL(3,1)"), (1, "sepal_width", "DECIMAL(3,1)"),
        (2, "petal_length", "DECIMAL(3,1)"), (3, "petal_width", "DECIMAL(3,1)"),
        (4, "species", "VARCHAR(12)")]

PENGUINS = [("species", "species", "VARCHAR(12)"), ("island", "island", "VARCHAR(12)"),
            ("bill_length_mm", "bill_length_mm", "DECIMAL(4,1)"),
            ("bill_depth_mm", "bill_depth_mm", "DECIMAL(4,1)"),
            ("flipper_length_mm", "flipper_length_mm", "SMALLINT UNSIGNED"),
            ("body_mass_g", "body_mass_g", "SMALLINT UNSIGNED"),
            ("sex", "sex", "VARCHAR(6)"), ("year", "year", "SMALLINT UNSIGNED")]

PENGUINS_RAW = [("studyName", "study_name", "VARCHAR(12)"), ("Sample Number", "sample_number", "SMALLINT UNSIGNED"),
                ("Species", "species", "VARCHAR(60)"), ("Region", "region", "VARCHAR(20)"),
                ("Island", "island", "VARCHAR(20)"), ("Stage", "stage", "VARCHAR(30)"),
                ("Individual ID", "individual_id", "VARCHAR(10)"),
                ("Clutch Completion", "clutch_completion", "VARCHAR(3)"),
                ("Date Egg", "date_egg", "DATE"), ("Culmen Length (mm)", "culmen_length_mm", "DECIMAL(4,1)"),
                ("Culmen Depth (mm)", "culmen_depth_mm", "DECIMAL(4,1)"),
                ("Flipper Length (mm)", "flipper_length_mm", "SMALLINT UNSIGNED"),
                ("Body Mass (g)", "body_mass_g", "SMALLINT UNSIGNED"), ("Sex", "sex", "VARCHAR(6)"),
                ("Delta 15 N (o/oo)", "delta_15_n", "DECIMAL(10,6)"),
                ("Delta 13 C (o/oo)", "delta_13_c", "DECIMAL(10,6)"),
                ("Comments", "comments", "VARCHAR(255)")]


def main():
    downloads, dest = sys.argv[1], sys.argv[2]
    parts = ["-- smallsets: Titanic, Iris and Palmer Penguins. Generated by datasets/smallsets/convert.py.",
             "-- Licences differ per table; see datasets/smallsets/LICENSE.",
             "SET NAMES utf8mb4;",
             "DROP DATABASE IF EXISTS `smallsets`;",
             "CREATE DATABASE `smallsets` DEFAULT CHARACTER SET utf8mb4;",
             "USE `smallsets`;"]
    total = {}
    for table, spec, filename, kwargs in [
            ("titanic", TITANIC, "titanic3.csv", {}),
            ("iris", IRIS, "iris.csv",
             {"header": "skip", "transform": lambda r: {**r, "species": SPECIES.get(r["species"], r["species"])}}),
            ("penguins", PENGUINS, "penguins.csv", {}),
            ("penguins_raw", PENGUINS_RAW, "penguins_raw.csv", {})]:
        sql, n = csvtable.emit_table(os.path.join(downloads, filename), table, spec,
                                     surrogate=f"{table}_id", **kwargs)
        parts.append(sql)
        total[table] = n
    open(dest, "w", encoding="utf-8").write("\n".join(parts) + "\n")
    print(f"  . converted {total}")


if __name__ == "__main__":
    main()
