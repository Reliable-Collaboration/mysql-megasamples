#!/usr/bin/env python3
"""Northwind: translate Microsoft's T-SQL install script to MySQL.

Emits statements in the order the indexing strategy requires (ARCHITECTURE.md section 4) -- tables (primary keys only), then data,
then secondary indexes, then foreign keys -- rather than in the upstream file's order, so the bulk
load runs without foreign-key checks and the constraints are validated once at the end.

Record: knowledge/datasets/pubs.md   Decision: knowledge/decisions/mssql-pubs-pubs-conversion-path.md
"""
import os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from megasamples.sources import tsql  # noqa: E402

# CK_Birthdate compares against getdate(); MySQL forbids non-deterministic functions in CHECK.
DROP_CHECKS = []
HEADER = """-- Northwind, translated from microsoft/sql-server-samples instpubs.sql by
-- datasets/pubs/convert.py. Upstream is MIT; see datasets/pubs/LICENSE.
SET NAMES utf8mb4;
SET SESSION foreign_key_checks = 0;
SET SESSION unique_checks = 0;
DROP DATABASE IF EXISTS `pubs`;
CREATE DATABASE `pubs` DEFAULT CHARACTER SET utf8mb4;
USE `pubs`;
"""
FOOTER = """SET SESSION unique_checks = 1;
SET SESSION foreign_key_checks = 1;
"""


def trigger_to_mysql(sql):
    """T-SQL triggers are statement-level and read the `inserted`/`deleted` pseudo-tables, which
    MySQL has no equivalent for: a MySQL trigger is row-level and uses NEW/OLD. That is a semantic
    rewrite, not a translation, so the trigger is reported rather than guessed at."""
    name = re.search(r"(?i)create\s+trigger\s+(?:`([^`]+)`|(\w+))", sql)
    label = f"`{name.group(1) or tsql.ident(name.group(2))}`" if name else "(unnamed)"
    return (f"-- UNPORTED TRIGGER {label}: T-SQL statement-level trigger using the inserted/deleted\n"
            f"--   pseudo-tables. MySQL triggers are row-level (NEW/OLD), so this needs a semantic\n"
            f"--   rewrite rather than a translation. Upstream text:\n" + comment_out(sql))


def check_completeness(src_sql, buckets, unported):
    """Fail the conversion if an upstream object is neither emitted nor explicitly reported.

    Silent loss is the failure mode that matters here: a dropped trigger or view does not break the
    load, it just quietly produces a less faithful database."""
    counts = {
        "table": len(re.findall(r"(?im)^\s*create\s+table\b", src_sql)),
        "view": len(re.findall(r"(?im)^\s*create\s+view\b", src_sql)),
        "procedure": len(re.findall(r"(?im)^\s*create\s+proc(edure)?\b", src_sql)),
        "trigger": len(re.findall(r"(?im)^\s*create\s+trigger\b", src_sql)),
    }
    problems = []
    for kind, expected in counts.items():
        got = len(buckets.get(kind, []))
        if got != expected:
            problems.append(f"{kind}: upstream has {expected}, conversion accounted for {got}")
    if problems:
        raise SystemExit("conversion is incomplete:\n  " + "\n  ".join(problems))
    return counts


def comment_out(sql):
    """Comment a statement out with line comments. A /* */ block cannot safely wrap T-SQL that may
    itself contain comment markers."""
    return "".join(f"--   {line}\n" for line in sql.strip().split("\n"))


def main():
    src, dest, mapfile = sys.argv[1], sys.argv[2], sys.argv[3]
    statements, name_map, notes = tsql.translate(open(src, encoding="utf-8").read(), drop_checks=DROP_CHECKS, dateformat="mdy")

    buckets = {k: [] for k in ("table", "dml", "index", "constraint", "view", "procedure", "trigger")}
    for st in statements:
        sql, kind = st["sql"], st["kind"]
        if kind == "other":
            if re.match(r"(?i)^\s*create\s+(unique\s+)?index", sql.strip()):
                buckets["index"].append(sql)
            continue                       # comments and banner text
        buckets[kind].append(sql)

    out = [HEADER]
    for phase in ("table", "dml", "index", "constraint", "view", "procedure", "trigger"):
        if not buckets[phase]:
            continue
        out.append(f"\n-- {'-' * 60}\n-- {phase}\n")
        for sql in buckets[phase]:
            if phase == "procedure":
                out.append(procedure_to_mysql(sql))
            elif phase == "trigger":
                out.append(trigger_to_mysql(sql))
            else:
                out.append(tsql.terminate(sql))
    out.append(FOOTER)
    open(dest, "w", encoding="utf-8").write("\n".join(out))
    with open(mapfile, "w", encoding="utf-8") as fh:
        fh.write("# Generated by datasets/pubs/convert.py: upstream identifier -> MySQL identifier.\n")
        for old, new in sorted(name_map.items()):
            fh.write(f"{old}: {new}\n")
    check_completeness(open(src, encoding="utf-8").read(), buckets, None)
    counts = {k: len(v) for k, v in buckets.items() if v}
    unported = len(re.findall(r"^-- UNPORTED", open(dest, encoding="utf-8").read(), re.M))
    print(f"  . translated {counts}, {len(name_map)} identifiers mapped, {unported} object(s) reported unported")
    for note in sorted(set(notes)):
        print(f"  . {note}")


def procedure_to_mysql(sql):
    """`create procedure X [@p type, ...] AS <body>` -> a MySQL routine.

    Parameters are renamed `@CustomerID` -> `p_CustomerID`: MySQL resolves an unqualified name that
    matches both a parameter and a column in favour of the column, which silently makes such a
    procedure return the wrong rows. `SET ROWCOUNT n` becomes a trailing LIMIT.
    """
    # the name may be quoted or bare; bare ones still need the naming convention applied
    m = re.match(r"(?is)^\s*create\s+procedure\s+(?:`([^`]+)`|(\w+))\s*(.*?)\bAS\b(.*)$", sql)
    if not m:
        return "-- UNPORTED PROCEDURE (unrecognised shape). Upstream text:\n" + comment_out(sql)
    name = f"`{m.group(1) or tsql.ident(m.group(2))}`"
    params, body = m.group(3).strip(), m.group(4).strip()
    # MySQL has no default parameter values; drop them and note it on the routine
    defaults = re.findall(r"@(\w+)\s+[A-Za-z]+\s*(?:\([^)]*\))?\s*=\s*('[^']*'|[\w.]+)", params)
    params = re.sub(r"(\s*=\s*(?:'[^']*'|[\w.]+))", "", params)

    signature = []
    for pname, ptype in re.findall(r"@(\w+)\s+([A-Za-z]+\s*(?:\(\s*[\d, ]+\s*\))?)", params):
        signature.append(f"IN p_{pname} {tsql._cast_type(ptype) if ptype.lower() not in tsql.TYPE_MAP else tsql.TYPE_MAP[ptype.lower()]}")
    body = re.sub(r"@(\w+)", r"p_\1", body)

    limit = ""
    rc = re.search(r"(?i)\bSET\s+ROWCOUNT\s+(\d+)", body)
    if rc:
        limit = f" LIMIT {rc.group(1)}"
        body = re.sub(r"(?i)\bSET\s+ROWCOUNT\s+\d+\s*", "", body).strip()
    # Constructs with no mechanical MySQL equivalent. Detect them here and refuse, rather than
    # emitting SQL that only fails when the image is built.
    blockers = []
    if re.search(r"(?is)\bSELECT\s+p_\w+\s*=", body):
        blockers.append("T-SQL variable assignment (SELECT @var = ...), which MySQL spells SET")
    if re.search(r"(?is)^\s*IF\b.*?\bBEGIN\b", body):
        blockers.append("T-SQL IF ... BEGIN/END, which MySQL spells IF ... THEN ... END IF")
    if re.search(r"(?im)^\s*\w+\s*=\s*(ROUND|SUM|COUNT|CONVERT|CAST)\b", body):
        blockers.append("T-SQL select-list aliasing (alias = expr), which MySQL spells expr AS alias")
    if blockers:
        reasons = "".join(f"--   - {b}\n" for b in blockers)
        return (f"-- UNPORTED PROCEDURE {name}: the body uses\n{reasons}"
                f"--   Port by hand if the routine is wanted; the data is unaffected. Upstream text:\n"
                + comment_out(sql))
    body = tsql.normalize_comments(body).rstrip().rstrip(";")
    note = ("".join(f"-- NOTE: parameter {n} had the default {v} upstream; MySQL has no default\n"
                    f"--       parameter values, so callers must pass it explicitly.\n"
                    for n, v in defaults))
    return (note + f"DELIMITER $$\nCREATE PROCEDURE {name}({', '.join(signature)})\nBEGIN\n"
            f"{body}{limit};\nEND$$\nDELIMITER ;\n")


if __name__ == "__main__":
    main()
